#!/usr/bin/env bun
/**
 * Export seeded git-commands.db → apps/web/public/catalog/web-pack.bin (+ .sha256).
 * Prints measured size for overlay constant.
 *
 * Usage: bun scripts/export-web-pack.js
 */

import { mkdirSync, writeFileSync, readFileSync, existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { openDb, loadAllRows, EMBEDDING_DIM } from '../packages/core/src/db/schema.js';
import { encodeWebPack } from '../packages/core/src/search/webPack.js';
import { defaultDbPath, defaultThresholdsPath, PACKAGE_ROOT } from '../packages/core/src/lib/paths.js';
import { writeChecksumFile, sha256Buffer } from '../packages/core/src/lib/checksum.js';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const outDir = path.join(PACKAGE_ROOT, 'apps', 'web', 'public', 'catalog');
const outBin = path.join(outDir, 'web-pack.bin');
const constantsOut = path.join(PACKAGE_ROOT, 'apps', 'web', 'src', 'lib', 'assetSizes.js');

const dbPath = process.env.GIT_HELP_DB || defaultDbPath();
const thresholdsPath = process.env.GIT_HELP_THRESHOLDS || defaultThresholdsPath();

if (!existsSync(dbPath)) {
  console.error(`Database missing: ${dbPath}. Run bun run seed first.`);
  process.exit(1);
}

const thresholds = JSON.parse(readFileSync(thresholdsPath, 'utf8'));
const db = openDb(dbPath, { readonly: true });

const metaRows = loadAllRows(db);
const embStmt = db.prepare('SELECT id, embedding FROM vec_commands');
const embById = new Map();
for (const row of embStmt.iterate()) {
  embById.set(row.id, row.embedding);
}

const rows = [];
for (const meta of metaRows) {
  const emb = embById.get(meta.id);
  if (!emb) {
    console.warn(`skip ${meta.id}: no embedding`);
    continue;
  }
  rows.push({
    ...meta,
    embedding: emb instanceof Uint8Array ? emb : new Uint8Array(emb),
  });
}
db.close();

console.log(`Encoding ${rows.length} rows (dim=${EMBEDDING_DIM})…`);
const packed = encodeWebPack({
  dim: EMBEDDING_DIM,
  thresholds,
  rows,
});

mkdirSync(outDir, { recursive: true });
writeFileSync(outBin, packed);
const hash = sha256Buffer(packed);
writeChecksumFile(outBin);

const packMb = packed.byteLength / (1024 * 1024);
// MiniLM ONNX via transformers.js is typically ~23MB quantized / ~90MB fp32.
// We ship fp32 for CLI parity; overlay cites pack + approximate model.
const MODEL_BYTES_ESTIMATE = 90 * 1024 * 1024;
const totalBytes = packed.byteLength + MODEL_BYTES_ESTIMATE;
const totalMb = Math.ceil(totalBytes / (1024 * 1024));

mkdirSync(path.dirname(constantsOut), { recursive: true });
writeFileSync(
  constantsOut,
  `/** Auto-generated by scripts/export-web-pack.js — do not edit by hand. */
export const WEB_PACK_BYTES = ${packed.byteLength};
export const WEB_PACK_SHA256 = '${hash}';
export const MODEL_BYTES_ESTIMATE = ${MODEL_BYTES_ESTIMATE};
export const PLAYGROUND_DOWNLOAD_MB = ${totalMb};
export const PLAYGROUND_DOWNLOAD_LABEL = '~${totalMb} MB';
`,
);

console.log(`Wrote ${outBin}`);
console.log(`Pack: ${packMb.toFixed(2)} MB (${packed.byteLength} bytes)`);
console.log(`SHA256: ${hash}`);
console.log(`Overlay constant PLAYGROUND_DOWNLOAD_MB = ${totalMb}`);
console.log(`Constants → ${constantsOut}`);
